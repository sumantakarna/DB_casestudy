-- Mirrors the rule set of STANDARD.CLASSIFY_BATCH (authoritative for curated state) for analytics and tests.
WITH dedup AS (
  SELECT * FROM {{ ref('stg_trade_events') }}
  WHERE EVENT_ID IS NOT NULL
  QUALIFY ROW_NUMBER() OVER (PARTITION BY EVENT_ID ORDER BY INGESTED_AT, SOURCE_FILE, FILE_ROW_NUMBER) = 1
), checks AS (
  SELECT *, ARRAY_CONSTRUCT_COMPACT(
    IFF(TRADE_ID IS NULL OR TRIM(TRADE_ID) = '' OR VERSION IS NULL OR CURRENCY IS NULL OR MATURITY_DATE IS NULL OR SIDE IS NULL, 'REQUIRED_FIELDS', NULL),
    IFF(COALESCE(VERSION < 1, FALSE), 'VERSION_INVALID', NULL),
    IFF(TRADE_DATE IS NULL OR MATURITY_DATE IS NULL, 'DATE_PARSE', NULL),
    IFF(NOTIONAL IS NULL OR NOTIONAL <= 0 OR PRICE IS NULL, 'NUMERIC_PARSE', NULL),
    IFF(COALESCE(SIDE NOT IN ('BUY','SELL'), TRUE) OR COALESCE(CURRENCY NOT IN ('USD','EUR','GBP','JPY','CHF','CAD','AUD'), TRUE), 'DOMAIN_VALUES', NULL),
    IFF(REGEXP_COUNT(COALESCE(TRADE_ID,'') || COALESCE(COUNTERPARTY,'') || COALESCE(INSTRUMENT,''), '[[:cntrl:]]') > 0
        OR CONTAINS(COALESCE(TRADE_ID,'') || COALESCE(COUNTERPARTY,'') || COALESCE(INSTRUMENT,''), CHR(65533)), 'CONTROL_CHARS', NULL),
    IFF(COALESCE(MATURITY_DATE < CURRENT_DATE(), FALSE), 'MATURITY_PAST', NULL)
  ) AS DQ_ERRORS
  FROM dedup
)
SELECT *, ARRAY_SIZE(DQ_ERRORS) = 0 AS IS_VALID, ARRAY_TO_STRING(DQ_ERRORS, ',') AS REJECT_REASON
FROM checks
