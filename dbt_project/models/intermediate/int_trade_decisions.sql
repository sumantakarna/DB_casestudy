WITH events AS (
  SELECT * FROM {{ ref('stg_trade_events') }}
  WHERE BATCH_ID = '{{ var("batch_id") }}'
),
structural AS (
  SELECT e.*,
    CASE
      WHEN TRADE_ID IS NULL OR TRIM(TRADE_ID) = '' THEN 'MISSING_TRADE_ID'
      WHEN VERSION IS NULL OR VERSION < 1 THEN 'INVALID_VERSION'
      WHEN INSTRUMENT IS NULL OR INSTRUMENT = '' THEN 'MISSING_INSTRUMENT'
      WHEN TRADE_SIDE NOT IN ('BUY','SELL') OR TRADE_SIDE IS NULL THEN 'INVALID_TRADE_SIDE'
      WHEN QUANTITY IS NULL OR QUANTITY <= 0 THEN 'INVALID_QUANTITY'
      WHEN PRICE IS NULL OR PRICE <= 0 THEN 'INVALID_PRICE'
      WHEN CURRENCY IS NULL OR LENGTH(CURRENCY) <> 3 THEN 'INVALID_CURRENCY'
      WHEN TRADE_DATE IS NULL THEN 'INVALID_TRADE_DATE'
      WHEN MATURITY_DATE IS NULL THEN 'INVALID_MATURITY_DATE'
      WHEN EVENT_TIMESTAMP IS NULL THEN 'INVALID_EVENT_TIMESTAMP'
      WHEN MATURITY_DATE < CURRENT_DATE() THEN 'MATURITY_BEFORE_TODAY'
      ELSE NULL
    END AS BASE_REJECTION_REASON
  FROM events e
),
ranked AS (
  SELECT s.*,
    ROW_NUMBER() OVER (
      PARTITION BY TRADE_ID ORDER BY VERSION DESC, EVENT_TIMESTAMP DESC, EVENT_ID DESC
    ) AS BATCH_RANK
  FROM structural s
  WHERE BASE_REJECTION_REASON IS NULL
),
state AS (
  SELECT TRADE_ID, VERSION FROM TRADE_DB.CURATED.CURRENT_TRADES
),
decisions AS (
  SELECT s.*, r.BATCH_RANK,
    CASE
      WHEN s.BASE_REJECTION_REASON IS NOT NULL THEN s.BASE_REJECTION_REASON
      WHEN r.BATCH_RANK > 1 THEN 'SUPERSEDED_IN_BATCH'
      WHEN c.TRADE_ID IS NOT NULL AND s.VERSION < c.VERSION THEN 'STALE_VERSION'
      ELSE NULL
    END AS REJECTION_REASON,
    CASE
      WHEN s.BASE_REJECTION_REASON IS NOT NULL THEN 'REJECTED'
      WHEN r.BATCH_RANK > 1 THEN 'REJECTED'
      WHEN c.TRADE_ID IS NOT NULL AND s.VERSION < c.VERSION THEN 'REJECTED'
      WHEN c.TRADE_ID IS NOT NULL AND s.VERSION = c.VERSION THEN 'SAME_VERSION_REPLACEMENT'
      ELSE 'ACCEPTED'
    END AS DECISION_STATUS
  FROM structural s
  LEFT JOIN ranked r ON s.EVENT_ID = r.EVENT_ID
  LEFT JOIN state c ON s.TRADE_ID = c.TRADE_ID
)
SELECT d.*,
  CASE WHEN DECISION_STATUS = 'REJECTED' THEN REJECTION_REASON END AS FINAL_REJECTION_REASON
FROM decisions d
