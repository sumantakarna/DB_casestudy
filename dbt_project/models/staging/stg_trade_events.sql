SELECT *
FROM (
  SELECT
    EVENT_ID::STRING AS EVENT_ID, TRADE_ID::STRING AS TRADE_ID,
    VERSION::NUMBER(38,0) AS VERSION, UPPER(INSTRUMENT)::STRING AS INSTRUMENT,
    UPPER(TRADE_SIDE)::STRING AS TRADE_SIDE, QUANTITY::NUMBER(38,8) AS QUANTITY,
    PRICE::NUMBER(38,8) AS PRICE, UPPER(CURRENCY)::STRING AS CURRENCY,
    TRADE_DATE::DATE AS TRADE_DATE, MATURITY_DATE::DATE AS MATURITY_DATE,
    COUNTERPARTY::STRING AS COUNTERPARTY, EVENT_TIMESTAMP::TIMESTAMP_NTZ AS EVENT_TIMESTAMP,
    SOURCE_SYSTEM::STRING AS SOURCE_SYSTEM, BATCH_ID::STRING AS BATCH_ID,
    INGESTED_AT::TIMESTAMP_NTZ AS INGESTED_AT, RAW_PAYLOAD
  FROM {{ source('raw', 'trade_events') }}
  WHERE EVENT_ID IS NOT NULL
)
QUALIFY ROW_NUMBER() OVER (PARTITION BY EVENT_ID ORDER BY INGESTED_AT DESC) = 1
