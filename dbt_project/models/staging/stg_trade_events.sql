SELECT EVENT_ID,SOURCE_SYSTEM,SOURCE_TYPE,BATCH_ID,TRADE_ID,
       TRY_TO_NUMBER(VERSION) AS VERSION,UPPER(EVENT_TYPE) AS EVENT_TYPE,
       TRY_TO_DATE(TRADE_DATE) AS TRADE_DATE,TRY_TO_DATE(MATURITY_DATE) AS MATURITY_DATE,
       COUNTERPARTY,UPPER(INSTRUMENT) AS INSTRUMENT,UPPER(CURRENCY) AS CURRENCY,
       TRY_TO_DECIMAL(NOTIONAL,38,2) AS NOTIONAL,TRY_TO_DECIMAL(PRICE,38,8) AS PRICE,
       UPPER(SIDE) AS SIDE,SOURCE_SEQUENCE,INGESTED_AT,SOURCE_FILE,PAYLOAD,
       IFF(TRADE_ID IS NULL OR VERSION IS NULL OR TRY_TO_DATE(MATURITY_DATE) IS NULL
           OR TRY_TO_DECIMAL(NOTIONAL,38,2)<=0 OR UPPER(SIDE) NOT IN ('BUY','SELL'),FALSE,TRUE) AS TECHNICALLY_VALID
FROM {{ source('raw','trade_events') }}
{% if var('batch_id', none) %} WHERE BATCH_ID='{{ var("batch_id") }}' {% endif %}
