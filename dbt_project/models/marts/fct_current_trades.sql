          on_schema_change='sync_all_columns') }}

SELECT
  TRADE_ID, VERSION, INSTRUMENT, TRADE_SIDE, QUANTITY, PRICE, CURRENCY, TRADE_DATE,
  MATURITY_DATE, COUNTERPARTY, EVENT_TIMESTAMP, SOURCE_SYSTEM, BATCH_ID, EVENT_ID,
  CASE WHEN MATURITY_DATE < CURRENT_DATE() THEN 'EXPIRED' ELSE 'VALID' END AS TRADE_STATUS,
  CURRENT_TIMESTAMP()::TIMESTAMP_NTZ AS LAST_PROCESSED_AT
FROM {{ ref('int_trade_decisions') }}
WHERE DECISION_STATUS IN ('ACCEPTED','SAME_VERSION_REPLACEMENT')
QUALIFY ROW_NUMBER() OVER (
  PARTITION BY TRADE_ID ORDER BY VERSION DESC, EVENT_TIMESTAMP DESC, EVENT_ID DESC
) = 1
