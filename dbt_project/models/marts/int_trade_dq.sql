WITH src AS (SELECT * FROM {{ ref('stg_trade_events') }}),
checks AS (
 SELECT *, ARRAY_CONSTRUCT_COMPACT(
   IFF(EVENT_ID IS NULL,'MISSING_EVENT_ID',NULL),
   IFF(TRADE_ID IS NULL,'MISSING_TRADE_ID',NULL),
   IFF(VERSION IS NULL OR VERSION<=0,'INVALID_VERSION',NULL),
   IFF(TRADE_DATE IS NULL,'INVALID_TRADE_DATE',NULL),
   IFF(MATURITY_DATE IS NULL,'INVALID_MATURITY_DATE',NULL),
   IFF(MATURITY_DATE<CURRENT_DATE(),'MATURITY_BEFORE_TODAY',NULL),
   IFF(NOTIONAL IS NULL OR NOTIONAL<=0,'INVALID_NOTIONAL',NULL),
   IFF(PRICE IS NULL,'INVALID_PRICE',NULL),
   IFF(CURRENCY NOT IN ('USD','EUR','GBP','JPY','CHF','CAD','AUD'),'INVALID_CURRENCY',NULL),
   IFF(SIDE NOT IN ('BUY','SELL'),'INVALID_SIDE',NULL),
   IFF(REGEXP_LIKE(COALESCE(TRADE_ID,''),'.*[[:cntrl:]].*'),'CONTROL_CHAR_TRADE_ID',NULL),
   IFF(COUNT(*) OVER(PARTITION BY TRADE_ID,VERSION,RECORD_HASH)>1,'DUPLICATE_TRADE_VERSION_PAYLOAD',NULL)
 ) AS DQ_ERRORS
 FROM src
), dedup AS (
 SELECT *, ROW_NUMBER() OVER(PARTITION BY EVENT_ID ORDER BY INGESTED_AT DESC) AS EVENT_RN
 FROM checks
)
SELECT *, IFF(ARRAY_SIZE(DQ_ERRORS)=0 AND EVENT_RN=1,TRUE,FALSE) AS IS_VALID,
       IFF(EVENT_RN>1,'DUPLICATE_EVENT_ID',ARRAY_TO_STRING(DQ_ERRORS,',')) AS REJECT_REASON
FROM dedup
