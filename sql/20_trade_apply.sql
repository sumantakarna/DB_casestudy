-- Apply classified events to history + current state. Serialize per batch (or per HASH(trade_id) partition at scale).
CREATE OR REPLACE PROCEDURE DB_TRADE_DB.CURATED.APPLY_BATCH(P_BATCH_ID STRING)
RETURNS STRING LANGUAGE SQL EXECUTE AS OWNER AS
$$
DECLARE
  v_status STRING; v_classified NUMBER; v_rows NUMBER;
  not_classified EXCEPTION (-20001, 'Batch must be classified, and RAW unchanged since classification, before apply.');
BEGIN
  SELECT STATUS, COALESCE(CLASSIFIED_ROWS, -1) INTO :v_status, :v_classified
  FROM DB_TRADE_DB.OPS.BATCH_CONTROL WHERE BATCH_ID = :P_BATCH_ID;
  SELECT COUNT(*) INTO :v_rows FROM DB_TRADE_DB.RAW.TRADE_EVENTS WHERE BATCH_ID = :P_BATCH_ID;
  IF (v_status IS NULL OR v_status NOT IN ('CLASSIFIED','APPLIED','RECONCILED','RECON_FAILED') OR v_classified <> v_rows) THEN
    RAISE not_classified;
  END IF;

  -- Deterministic clean event set, built before the DML transaction (DDL would commit it).
  CREATE OR REPLACE TEMP TABLE TMP_VALID_TRADE_EVENTS AS
  SELECT R.EVENT_ID,R.BATCH_ID,R.TRADE_ID,R.VERSION,R.EVENT_TYPE,
         TRY_TO_DATE(R.TRADE_DATE) TRADE_DATE,TRY_TO_DATE(R.MATURITY_DATE) MATURITY_DATE,
         R.COUNTERPARTY,R.INSTRUMENT,UPPER(R.CURRENCY) CURRENCY,
         TRY_TO_DECIMAL(R.NOTIONAL,38,2) NOTIONAL,TRY_TO_DECIMAL(R.PRICE,38,8) PRICE,
         UPPER(R.SIDE) SIDE,R.SOURCE_SYSTEM,R.RECORD_HASH,R.INGESTED_AT,R.SOURCE_SEQUENCE,R.PAYLOAD,R.SOURCE_FILE
  FROM DB_TRADE_DB.STANDARD.V_RAW_EVENTS R
  WHERE R.BATCH_ID = :P_BATCH_ID
    AND NOT EXISTS (SELECT 1 FROM DB_TRADE_DB.AUDIT.DQ_RESULTS D
                    WHERE D.EVENT_ID = R.EVENT_KEY AND D.BATCH_ID = R.BATCH_ID AND D.SEVERITY = 'ERROR')
  QUALIFY ROW_NUMBER() OVER (PARTITION BY R.TRADE_ID, R.VERSION
          ORDER BY R.SOURCE_SEQUENCE DESC NULLS LAST, R.INGESTED_AT DESC, R.EVENT_ID DESC) = 1;

  BEGIN TRANSACTION;
  DELETE FROM DB_TRADE_DB.AUDIT.REJECTED_TRADES WHERE BATCH_ID = :P_BATCH_ID AND REJECT_REASON = 'STALE_VERSION';
  INSERT INTO DB_TRADE_DB.AUDIT.REJECTED_TRADES (EVENT_ID,BATCH_ID,TRADE_ID,VERSION,REJECT_REASON,RAW_PAYLOAD,SOURCE_SYSTEM,SOURCE_FILE)
  SELECT V.EVENT_ID,V.BATCH_ID,V.TRADE_ID,V.VERSION,'STALE_VERSION',V.PAYLOAD,V.SOURCE_SYSTEM,V.SOURCE_FILE
  FROM TMP_VALID_TRADE_EVENTS V JOIN DB_TRADE_DB.CURATED.CURRENT_TRADES C ON C.TRADE_ID = V.TRADE_ID
  WHERE V.VERSION < C.VERSION;

  INSERT INTO DB_TRADE_DB.CURATED.TRADE_HISTORY (EVENT_ID,TRADE_ID,VERSION,EVENT_TYPE,TRADE_DATE,MATURITY_DATE,COUNTERPARTY,INSTRUMENT,CURRENCY,NOTIONAL,PRICE,SIDE,SOURCE_SYSTEM,BATCH_ID,RECORD_HASH,EFFECTIVE_AT)
  SELECT V.EVENT_ID,V.TRADE_ID,V.VERSION,V.EVENT_TYPE,V.TRADE_DATE,V.MATURITY_DATE,V.COUNTERPARTY,V.INSTRUMENT,V.CURRENCY,V.NOTIONAL,V.PRICE,V.SIDE,V.SOURCE_SYSTEM,V.BATCH_ID,V.RECORD_HASH,V.INGESTED_AT
  FROM TMP_VALID_TRADE_EVENTS V
  LEFT JOIN DB_TRADE_DB.CURATED.CURRENT_TRADES C ON C.TRADE_ID = V.TRADE_ID
  WHERE (C.TRADE_ID IS NULL OR V.VERSION >= C.VERSION)
    AND NOT EXISTS (SELECT 1 FROM DB_TRADE_DB.CURATED.TRADE_HISTORY H WHERE H.EVENT_ID = V.EVENT_ID);

  MERGE INTO DB_TRADE_DB.CURATED.CURRENT_TRADES T
  USING (
    SELECT V.* FROM TMP_VALID_TRADE_EVENTS V
    LEFT JOIN DB_TRADE_DB.CURATED.CURRENT_TRADES C ON C.TRADE_ID = V.TRADE_ID
    WHERE C.TRADE_ID IS NULL OR V.VERSION >= C.VERSION
    QUALIFY ROW_NUMBER() OVER (PARTITION BY V.TRADE_ID
            ORDER BY V.VERSION DESC, V.SOURCE_SEQUENCE DESC NULLS LAST, V.INGESTED_AT DESC, V.EVENT_ID DESC) = 1
  ) S ON T.TRADE_ID = S.TRADE_ID
  WHEN MATCHED THEN UPDATE SET
    VERSION=S.VERSION,EVENT_ID=S.EVENT_ID,TRADE_DATE=S.TRADE_DATE,MATURITY_DATE=S.MATURITY_DATE,
    COUNTERPARTY=S.COUNTERPARTY,INSTRUMENT=S.INSTRUMENT,CURRENCY=S.CURRENCY,NOTIONAL=S.NOTIONAL,
    PRICE=S.PRICE,SIDE=S.SIDE,
    TRADE_STATUS=IFF(S.EVENT_TYPE='CANCEL','CANCELLED',IFF(S.MATURITY_DATE<CURRENT_DATE(),'EXPIRED','ACTIVE')),
    SOURCE_SYSTEM=S.SOURCE_SYSTEM,BATCH_ID=S.BATCH_ID,RECORD_HASH=S.RECORD_HASH,UPDATED_AT=CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN INSERT (TRADE_ID,VERSION,EVENT_ID,TRADE_DATE,MATURITY_DATE,COUNTERPARTY,INSTRUMENT,CURRENCY,NOTIONAL,PRICE,SIDE,TRADE_STATUS,SOURCE_SYSTEM,BATCH_ID,RECORD_HASH)
    VALUES (S.TRADE_ID,S.VERSION,S.EVENT_ID,S.TRADE_DATE,S.MATURITY_DATE,S.COUNTERPARTY,S.INSTRUMENT,S.CURRENCY,S.NOTIONAL,S.PRICE,S.SIDE,
            IFF(S.EVENT_TYPE='CANCEL','CANCELLED',IFF(S.MATURITY_DATE<CURRENT_DATE(),'EXPIRED','ACTIVE')),S.SOURCE_SYSTEM,S.BATCH_ID,S.RECORD_HASH);

  UPDATE DB_TRADE_DB.CURATED.CURRENT_TRADES SET TRADE_STATUS='EXPIRED', UPDATED_AT=CURRENT_TIMESTAMP()
  WHERE MATURITY_DATE < CURRENT_DATE() AND TRADE_STATUS = 'ACTIVE';
  UPDATE DB_TRADE_DB.OPS.BATCH_CONTROL SET STATUS='APPLIED', UPDATED_AT=CURRENT_TIMESTAMP() WHERE BATCH_ID = :P_BATCH_ID;
  COMMIT;
  RETURN 'APPLIED ' || P_BATCH_ID;
EXCEPTION WHEN OTHER THEN
  ROLLBACK;
  RAISE;
END;
$$;

-- Persist EXPIRED for trades whose maturity has passed (schedule daily, e.g. with a Snowflake TASK).
CREATE OR REPLACE PROCEDURE DB_TRADE_DB.CURATED.REFRESH_TRADE_STATUS()
RETURNS STRING LANGUAGE SQL EXECUTE AS OWNER AS
$$
BEGIN
  UPDATE DB_TRADE_DB.CURATED.CURRENT_TRADES SET TRADE_STATUS='EXPIRED', UPDATED_AT=CURRENT_TIMESTAMP()
  WHERE MATURITY_DATE < CURRENT_DATE() AND TRADE_STATUS = 'ACTIVE';
  RETURN 'EXPIRED ROWS: ' || SQLROWCOUNT;
END;
$$;
