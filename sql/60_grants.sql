-- Run last, as SECURITYADMIN/ACCOUNTADMIN. Least privilege per workload; assign roles to service users.
CREATE ROLE IF NOT EXISTS TRADE_INGEST_ROLE;     -- loaders / Kafka connector
CREATE ROLE IF NOT EXISTS TRADE_TRANSFORM_ROLE;  -- dbt + Airflow procedure calls
CREATE ROLE IF NOT EXISTS TRADE_BI_ROLE;         -- Streamlit / BI read-only

GRANT USAGE ON DATABASE DB_TRADE_DB TO ROLE TRADE_INGEST_ROLE;
GRANT USAGE ON DATABASE DB_TRADE_DB TO ROLE TRADE_TRANSFORM_ROLE;
GRANT USAGE ON DATABASE DB_TRADE_DB TO ROLE TRADE_BI_ROLE;
GRANT USAGE ON WAREHOUSE TRADE_LOAD_WH TO ROLE TRADE_INGEST_ROLE;
GRANT USAGE ON WAREHOUSE TRADE_TRANSFORM_WH TO ROLE TRADE_TRANSFORM_ROLE;
GRANT USAGE ON WAREHOUSE TRADE_BI_WH TO ROLE TRADE_BI_ROLE;

-- Ingest: write RAW, register manifests.
GRANT USAGE ON SCHEMA DB_TRADE_DB.RAW TO ROLE TRADE_INGEST_ROLE;
GRANT USAGE ON SCHEMA DB_TRADE_DB.OPS TO ROLE TRADE_INGEST_ROLE;
GRANT SELECT, INSERT ON TABLE DB_TRADE_DB.RAW.TRADE_EVENTS TO ROLE TRADE_INGEST_ROLE;
GRANT READ, WRITE ON STAGE DB_TRADE_DB.RAW.TRADE_INT_STAGE TO ROLE TRADE_INGEST_ROLE;
GRANT USAGE ON ALL FILE FORMATS IN SCHEMA DB_TRADE_DB.RAW TO ROLE TRADE_INGEST_ROLE;
GRANT USAGE ON PROCEDURE DB_TRADE_DB.OPS.REGISTER_MANIFEST(VARIANT) TO ROLE TRADE_INGEST_ROLE;

-- Transform: read RAW; own STANDARD (dbt); call procedures (they run as owner).
GRANT USAGE ON ALL SCHEMAS IN DATABASE DB_TRADE_DB TO ROLE TRADE_TRANSFORM_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA DB_TRADE_DB.RAW TO ROLE TRADE_TRANSFORM_ROLE;
GRANT SELECT ON ALL VIEWS IN SCHEMA DB_TRADE_DB.STANDARD TO ROLE TRADE_TRANSFORM_ROLE;
GRANT CREATE TABLE, CREATE VIEW ON SCHEMA DB_TRADE_DB.STANDARD TO ROLE TRADE_TRANSFORM_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA DB_TRADE_DB.OPS TO ROLE TRADE_TRANSFORM_ROLE;
GRANT USAGE ON PROCEDURE DB_TRADE_DB.STANDARD.CLASSIFY_BATCH(STRING) TO ROLE TRADE_TRANSFORM_ROLE;
GRANT USAGE ON PROCEDURE DB_TRADE_DB.CURATED.APPLY_BATCH(STRING) TO ROLE TRADE_TRANSFORM_ROLE;
GRANT USAGE ON PROCEDURE DB_TRADE_DB.OPS.RECONCILE_BATCH(STRING) TO ROLE TRADE_TRANSFORM_ROLE;
GRANT USAGE ON PROCEDURE DB_TRADE_DB.CURATED.REFRESH_TRADE_STATUS() TO ROLE TRADE_TRANSFORM_ROLE;
GRANT UPDATE ON TABLE DB_TRADE_DB.OPS.BATCH_CONTROL TO ROLE TRADE_TRANSFORM_ROLE;  -- Airflow marks LATE batches

-- BI: read-only on curated, audit and ops.
GRANT USAGE ON SCHEMA DB_TRADE_DB.CURATED TO ROLE TRADE_BI_ROLE;
GRANT USAGE ON SCHEMA DB_TRADE_DB.AUDIT TO ROLE TRADE_BI_ROLE;
GRANT USAGE ON SCHEMA DB_TRADE_DB.OPS TO ROLE TRADE_BI_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA DB_TRADE_DB.CURATED TO ROLE TRADE_BI_ROLE;
GRANT SELECT ON ALL VIEWS IN SCHEMA DB_TRADE_DB.CURATED TO ROLE TRADE_BI_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA DB_TRADE_DB.AUDIT TO ROLE TRADE_BI_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA DB_TRADE_DB.OPS TO ROLE TRADE_BI_ROLE;
