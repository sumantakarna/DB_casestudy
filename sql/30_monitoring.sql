-- Recent ingestion health: use Information Schema COPY_HISTORY for operational checks.
SELECT * FROM TABLE(DB_TRADE_DB.INFORMATION_SCHEMA.COPY_HISTORY(
  TABLE_NAME=>'RAW.TRADE_EVENTS', START_TIME=>DATEADD('hour',-24,CURRENT_TIMESTAMP())))
ORDER BY LAST_LOAD_TIME DESC;

-- Query performance / failed statements (ACCOUNT_USAGE may have latency).
SELECT QUERY_ID,USER_NAME,WAREHOUSE_NAME,EXECUTION_STATUS,ERROR_CODE,ERROR_MESSAGE,
       TOTAL_ELAPSED_TIME/1000 AS ELAPSED_SECONDS,BYTES_SCANNED,ROWS_PRODUCED,START_TIME
FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
WHERE START_TIME>=DATEADD('day',-1,CURRENT_TIMESTAMP())
  AND (EXECUTION_STATUS='FAIL' OR TOTAL_ELAPSED_TIME>300000)
ORDER BY START_TIME DESC;

-- Warehouse consumption by workload.
SELECT WAREHOUSE_NAME,DATE_TRUNC('hour',START_TIME) HOUR,
       SUM(CREDITS_USED) CREDITS
FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY
WHERE START_TIME>=DATEADD('day',-7,CURRENT_TIMESTAMP())
GROUP BY 1,2 ORDER BY 2 DESC;

-- Task failures.
SELECT NAME,STATE,ERROR_CODE,ERROR_MESSAGE,SCHEDULED_TIME,COMPLETED_TIME
FROM SNOWFLAKE.ACCOUNT_USAGE.TASK_HISTORY
WHERE SCHEDULED_TIME>=DATEADD('day',-7,CURRENT_TIMESTAMP()) AND STATE='FAILED'
ORDER BY SCHEDULED_TIME DESC;

-- Duplicate file loads: retain own FILE_MANIFEST/file ledger as authoritative beyond load-history retention.
SELECT SOURCE_FILE,COUNT(*) AS ROWS_LOADED,COUNT(DISTINCT BATCH_ID) AS BATCHES
FROM DB_TRADE_DB.RAW.TRADE_EVENTS
WHERE INGESTED_AT>=DATEADD('day',-7,CURRENT_TIMESTAMP())
GROUP BY SOURCE_FILE HAVING COUNT(DISTINCT BATCH_ID)>1;

