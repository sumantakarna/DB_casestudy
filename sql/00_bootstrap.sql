-- Record-level classifier. One set-based pass evaluates every rule; no row-by-row UDFs.
-- ERROR rows are rejected. INFO rows (duplicates) are suppressed, not rejected: one copy still flows on.
CREATE OR REPLACE PROCEDURE DB_TRADE_DB.STANDARD.CLASSIFY_BATCH(P_BATCH_ID STRING)
RETURNS STRING LANGUAGE SQL EXECUTE AS OWNER AS
$$
BEGIN
  BEGIN TRANSACTION;
  DELETE FROM DB_TRADE_DB.AUDIT.DQ_RESULTS WHERE BATCH_ID = :P_BATCH_ID;
  DELETE FROM DB_TRADE_DB.AUDIT.REJECTED_TRADES WHERE BATCH_ID = :P_BATCH_ID;

  INSERT INTO DB_TRADE_DB.AUDIT.DQ_RESULTS (BATCH_ID,EVENT_ID,TRADE_ID,RULE_ID,SEVERITY,REASON)
  WITH BASE AS (
    SELECT V.*,
           COUNT(*) OVER (PARTITION BY EVENT_KEY) AS EVENT_KEY_COUNT,
           MIN(RECORD_HASH) OVER (PARTITION BY EVENT_KEY) AS HASH_MIN,
           MAX(RECORD_HASH) OVER (PARTITION BY EVENT_KEY) AS HASH_MAX,
           ROW_NUMBER() OVER (PARTITION BY EVENT_KEY ORDER BY INGESTED_AT, SOURCE_FILE, FILE_ROW_NUMBER) AS EVENT_RN,
           ROW_NUMBER() OVER (PARTITION BY TRADE_ID, VERSION, RECORD_HASH ORDER BY INGESTED_AT, SOURCE_FILE, FILE_ROW_NUMBER) AS PAYLOAD_RN
    FROM DB_TRADE_DB.STANDARD.V_RAW_EVENTS V
    WHERE V.BATCH_ID = :P_BATCH_ID
  )
  SELECT B.BATCH_ID, B.EVENT_KEY, B.TRADE_ID, F.VALUE:RULE_ID::STRING, F.VALUE:SEVERITY::STRING, F.VALUE:REASON::STRING
  FROM BASE B,
  LATERAL FLATTEN(INPUT => ARRAY_CONSTRUCT_COMPACT(
    IFF(B.EVENT_ID IS NULL OR B.TRADE_ID IS NULL OR TRIM(B.TRADE_ID) = '' OR B.VERSION IS NULL
        OR B.CURRENCY IS NULL OR B.MATURITY_DATE IS NULL OR B.SIDE IS NULL,
        OBJECT_CONSTRUCT('RULE_ID','REQUIRED_FIELDS','SEVERITY','ERROR','REASON','Missing mandatory field'), NULL),
    IFF(COALESCE(B.VERSION < 1, FALSE),
        OBJECT_CONSTRUCT('RULE_ID','VERSION_INVALID','SEVERITY','ERROR','REASON','Version must be >= 1'), NULL),
    IFF(TRY_TO_DATE(B.TRADE_DATE) IS NULL OR TRY_TO_DATE(B.MATURITY_DATE) IS NULL,
        OBJECT_CONSTRUCT('RULE_ID','DATE_PARSE','SEVERITY','ERROR','REASON','Invalid trade/maturity date'), NULL),
    IFF(TRY_TO_DECIMAL(B.NOTIONAL,38,2) IS NULL OR TRY_TO_DECIMAL(B.NOTIONAL,38,2) <= 0 OR TRY_TO_DECIMAL(B.PRICE,38,8) IS NULL,
        OBJECT_CONSTRUCT('RULE_ID','NUMERIC_PARSE','SEVERITY','ERROR','REASON','Invalid/non-positive notional or invalid price'), NULL),
    IFF(COALESCE(UPPER(B.SIDE) NOT IN ('BUY','SELL'), TRUE)
        OR COALESCE(UPPER(B.CURRENCY) NOT IN ('USD','EUR','GBP','JPY','CHF','CAD','AUD'), TRUE),
        OBJECT_CONSTRUCT('RULE_ID','DOMAIN_VALUES','SEVERITY','ERROR','REASON','Invalid side or currency'), NULL),
    IFF(REGEXP_COUNT(COALESCE(B.TRADE_ID,'') || COALESCE(B.COUNTERPARTY,'') || COALESCE(B.INSTRUMENT,''), '[[:cntrl:]]') > 0
        OR CONTAINS(COALESCE(B.TRADE_ID,'') || COALESCE(B.COUNTERPARTY,'') || COALESCE(B.INSTRUMENT,''), CHR(65533)),
        OBJECT_CONSTRUCT('RULE_ID','CONTROL_CHARS','SEVERITY','ERROR','REASON','Unreadable/control characters in text fields'), NULL),
    IFF(COALESCE(TRY_TO_DATE(B.MATURITY_DATE) < CURRENT_DATE(), FALSE),
        OBJECT_CONSTRUCT('RULE_ID','MATURITY_PAST','SEVERITY','ERROR','REASON','Maturity date earlier than processing date'), NULL),
    IFF(B.EVENT_KEY_COUNT > 1 AND COALESCE(B.HASH_MIN <> B.HASH_MAX, FALSE),
        OBJECT_CONSTRUCT('RULE_ID','EVENT_ID_CONFLICT','SEVERITY','ERROR','REASON','Same event ID delivered with different content'), NULL),
    IFF(B.EVENT_RN > 1 OR (B.RECORD_HASH IS NOT NULL AND B.PAYLOAD_RN > 1),
        OBJECT_CONSTRUCT('RULE_ID','DUPLICATE_SUPPRESSED','SEVERITY','INFO','REASON','Duplicate delivery of identical content (one copy kept)'), NULL)
  )) F;

  INSERT INTO DB_TRADE_DB.AUDIT.REJECTED_TRADES (EVENT_ID,BATCH_ID,TRADE_ID,VERSION,REJECT_REASON,RAW_PAYLOAD,SOURCE_SYSTEM,SOURCE_FILE)
  WITH REASONS AS (
    SELECT EVENT_ID, LISTAGG(DISTINCT REASON, '; ') WITHIN GROUP (ORDER BY REASON) AS REJECT_REASON
    FROM DB_TRADE_DB.AUDIT.DQ_RESULTS
    WHERE BATCH_ID = :P_BATCH_ID AND SEVERITY = 'ERROR'
    GROUP BY EVENT_ID
  )
  SELECT R.EVENT_KEY, R.BATCH_ID, R.TRADE_ID, R.VERSION, X.REJECT_REASON,
         COALESCE(R.PAYLOAD, TRY_PARSE_JSON(R.RAW_PAYLOAD)), R.SOURCE_SYSTEM, R.SOURCE_FILE
  FROM DB_TRADE_DB.STANDARD.V_RAW_EVENTS R
  JOIN REASONS X ON X.EVENT_ID = R.EVENT_KEY
  WHERE R.BATCH_ID = :P_BATCH_ID
  QUALIFY ROW_NUMBER() OVER (PARTITION BY R.EVENT_KEY ORDER BY R.INGESTED_AT, R.SOURCE_FILE, R.FILE_ROW_NUMBER) = 1;

  UPDATE DB_TRADE_DB.OPS.BATCH_CONTROL
     SET STATUS = 'CLASSIFIED',
         CLASSIFIED_ROWS = (SELECT COUNT(*) FROM DB_TRADE_DB.RAW.TRADE_EVENTS WHERE BATCH_ID = :P_BATCH_ID),
         UPDATED_AT = CURRENT_TIMESTAMP()
   WHERE BATCH_ID = :P_BATCH_ID;
  COMMIT;
  RETURN 'CLASSIFIED ' || P_BATCH_ID;
EXCEPTION WHEN OTHER THEN
  ROLLBACK;
  RAISE;
END;
$$;

-- Expiry is a lifecycle state, not a data-quality rejection: evaluated at query time here,
-- and persisted by CURATED.REFRESH_TRADE_STATUS() (20_trade_apply.sql).
CREATE OR REPLACE VIEW DB_TRADE_DB.CURATED.V_CURRENT_TRADES AS
SELECT *, IFF(TRADE_STATUS = 'CANCELLED', 'CANCELLED', IFF(MATURITY_DATE < CURRENT_DATE(), 'EXPIRED', 'ACTIVE')) AS DERIVED_LIFECYCLE_STATUS
FROM DB_TRADE_DB.CURATED.CURRENT_TRADES;
