-- RAW rows may arrive without an EVENT_ID (that is itself a DQ failure). EVENT_KEY gives every row a
-- stable identity so DQ results, rejects and apply logic can all join on it without NULL-join gaps.
CREATE OR REPLACE VIEW DB_TRADE_DB.STANDARD.V_RAW_EVENTS AS
SELECT E.*,
       COALESCE(E.EVENT_ID,
                'MISSING:' || COALESCE(E.SOURCE_FILE,'?') || ':' ||
                COALESCE(TO_VARCHAR(E.FILE_ROW_NUMBER), SHA2(COALESCE(TO_JSON(E.PAYLOAD), E.RAW_PAYLOAD, '')))) AS EVENT_KEY
FROM DB_TRADE_DB.RAW.TRADE_EVENTS E;

-- Register a producer manifest after all source objects have been uploaded and loaded.
-- The manifest is the batch commit signal; it also carries per-currency control totals.
CREATE OR REPLACE PROCEDURE DB_TRADE_DB.OPS.REGISTER_MANIFEST(P_MANIFEST VARIANT)
RETURNS STRING LANGUAGE SQL EXECUTE AS OWNER AS
$$
BEGIN
  MERGE INTO DB_TRADE_DB.OPS.BATCH_CONTROL T
  USING (SELECT GET(:P_MANIFEST,'batch_id')::STRING AS BATCH_ID,
                GET(:P_MANIFEST,'source_system')::STRING AS SOURCE_SYSTEM,
                GET(:P_MANIFEST,'expected_files')::NUMBER AS EXPECTED_FILES,
                GET(:P_MANIFEST,'expected_records')::NUMBER AS EXPECTED_RECORDS) S
  ON T.BATCH_ID = S.BATCH_ID
  WHEN MATCHED THEN UPDATE SET SOURCE_SYSTEM=S.SOURCE_SYSTEM, EXPECTED_FILES=S.EXPECTED_FILES,
       EXPECTED_RECORDS=S.EXPECTED_RECORDS, MANIFEST_RECEIVED=TRUE, STATUS='MANIFEST_RECEIVED',
       UPDATED_AT=CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN INSERT (BATCH_ID,SOURCE_SYSTEM,EXPECTED_FILES,EXPECTED_RECORDS,MANIFEST_RECEIVED,STATUS,STARTED_AT)
       VALUES (S.BATCH_ID,S.SOURCE_SYSTEM,S.EXPECTED_FILES,S.EXPECTED_RECORDS,TRUE,'MANIFEST_RECEIVED',CURRENT_TIMESTAMP());

  INSERT INTO DB_TRADE_DB.OPS.FILE_MANIFEST (BATCH_ID,SOURCE_SYSTEM,FILE_NAME,FILE_FORMAT,EXPECTED_RECORDS,EXPECTED_BYTES,EXPECTED_SHA256,ARRIVED_AT,STATUS)
  SELECT GET(:P_MANIFEST,'batch_id')::STRING, GET(:P_MANIFEST,'source_system')::STRING,
         F.VALUE:file_name::STRING, F.VALUE:format::STRING, F.VALUE:expected_records::NUMBER,
         F.VALUE:bytes::NUMBER, F.VALUE:sha256::STRING, CURRENT_TIMESTAMP(), 'REGISTERED'
  FROM TABLE(FLATTEN(INPUT => GET(:P_MANIFEST,'files'))) F
  WHERE NOT EXISTS (SELECT 1 FROM DB_TRADE_DB.OPS.FILE_MANIFEST X
                    WHERE X.BATCH_ID = GET(:P_MANIFEST,'batch_id')::STRING
                      AND X.FILE_NAME = F.VALUE:file_name::STRING);

  DELETE FROM DB_TRADE_DB.OPS.BATCH_CONTROL_TOTALS WHERE BATCH_ID = GET(:P_MANIFEST,'batch_id')::STRING;
  INSERT INTO DB_TRADE_DB.OPS.BATCH_CONTROL_TOTALS (BATCH_ID,CURRENCY,EXPECTED_NOTIONAL)
  SELECT GET(:P_MANIFEST,'batch_id')::STRING, UPPER(F.KEY::STRING), F.VALUE::NUMBER(38,2)
  FROM TABLE(FLATTEN(INPUT => GET(:P_MANIFEST,'control_totals'))) F;

  RETURN 'REGISTERED ' || GET(:P_MANIFEST,'batch_id')::STRING;
END;
$$;

