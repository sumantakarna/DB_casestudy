-- Record-level classifier. This procedure is intentionally set-based.
CREATE OR REPLACE PROCEDURE DB_TRADE_DB.STANDARD.CLASSIFY_BATCH(P_BATCH_ID STRING)
RETURNS STRING LANGUAGE SQL EXECUTE AS OWNER AS
$$
BEGIN
  DELETE FROM DB_TRADE_DB.AUDIT.DQ_RESULTS WHERE BATCH_ID=:P_BATCH_ID;
  DELETE FROM DB_TRADE_DB.AUDIT.REJECTED_TRADES WHERE BATCH_ID=:P_BATCH_ID;
  INSERT INTO DB_TRADE_DB.AUDIT.DQ_RESULTS(BATCH_ID,EVENT_ID,TRADE_ID,RULE_ID,SEVERITY,REASON)
  WITH BASE AS (
    SELECT *, COUNT(*) OVER(PARTITION BY EVENT_ID) AS EVENT_ID_COUNT,
              COUNT(*) OVER(PARTITION BY TRADE_ID,VERSION,RECORD_HASH) AS TRADE_VERSION_HASH_COUNT
    FROM DB_TRADE_DB.RAW.TRADE_EVENTS WHERE BATCH_ID=:P_BATCH_ID
  )
  SELECT B.BATCH_ID,B.EVENT_ID,B.TRADE_ID,F.VALUE:RULE_ID::STRING,'ERROR',F.VALUE:REASON::STRING
  FROM BASE B,
  LATERAL FLATTEN(INPUT=>ARRAY_CONSTRUCT_COMPACT(
    IFF(B.EVENT_ID IS NULL OR B.TRADE_ID IS NULL OR B.VERSION IS NULL OR B.CURRENCY IS NULL OR B.MATURITY_DATE IS NULL,
        OBJECT_CONSTRUCT('RULE_ID','REQUIRED_FIELDS','REASON','Missing mandatory field'),NULL),
    IFF(B.EVENT_ID_COUNT>1,OBJECT_CONSTRUCT('RULE_ID','DUPLICATE_EVENT_ID','REASON','Duplicate source event ID in batch'),NULL),
    IFF(B.RECORD_HASH IS NOT NULL AND B.TRADE_VERSION_HASH_COUNT>1,
        OBJECT_CONSTRUCT('RULE_ID','DUPLICATE_TRADE_VERSION_PAYLOAD','REASON','Duplicate trade/version with identical payload'),NULL),
    IFF(TRY_TO_DATE(B.TRADE_DATE) IS NULL OR TRY_TO_DATE(B.MATURITY_DATE) IS NULL,
        OBJECT_CONSTRUCT('RULE_ID','DATE_PARSE','REASON','Invalid trade/maturity date'),NULL),
    IFF(TRY_TO_DECIMAL(B.NOTIONAL,38,2) IS NULL OR TRY_TO_DECIMAL(B.NOTIONAL,38,2)<=0 OR TRY_TO_DECIMAL(B.PRICE,38,8) IS NULL,
        OBJECT_CONSTRUCT('RULE_ID','NUMERIC_PARSE','REASON','Invalid/non-positive notional or invalid price'),NULL),
    IFF(UPPER(B.SIDE) NOT IN ('BUY','SELL') OR UPPER(B.CURRENCY) NOT IN ('USD','EUR','GBP','JPY','CHF','CAD','AUD'),
        OBJECT_CONSTRUCT('RULE_ID','DOMAIN_VALUES','REASON','Invalid side or currency'),NULL),
    IFF(REGEXP_LIKE(COALESCE(B.TRADE_ID,''),'.*[[:cntrl:]].*') OR REGEXP_LIKE(COALESCE(B.COUNTERPARTY,''),'.*[[:cntrl:]].*'),
        OBJECT_CONSTRUCT('RULE_ID','CONTROL_CHARS','REASON','Unreadable/control characters in identifiers'),NULL),
    IFF(TRY_TO_DATE(B.MATURITY_DATE)<CURRENT_DATE(),
        OBJECT_CONSTRUCT('RULE_ID','MATURITY_PAST','REASON','Maturity date earlier than processing date'),NULL)
  )) F;

  INSERT INTO DB_TRADE_DB.AUDIT.REJECTED_TRADES(EVENT_ID,BATCH_ID,TRADE_ID,VERSION,REJECT_REASON,RAW_PAYLOAD,SOURCE_SYSTEM,SOURCE_FILE)
  SELECT R.EVENT_ID,R.BATCH_ID,R.TRADE_ID,R.VERSION,
         LISTAGG(DISTINCT D.REASON,'; ') WITHIN GROUP(ORDER BY D.REASON),
         COALESCE(R.PAYLOAD,TRY_PARSE_JSON(R.RAW_PAYLOAD)),R.SOURCE_SYSTEM,R.SOURCE_FILE
  FROM DB_TRADE_DB.RAW.TRADE_EVENTS R
  JOIN DB_TRADE_DB.AUDIT.DQ_RESULTS D ON D.EVENT_ID=R.EVENT_ID AND D.BATCH_ID=R.BATCH_ID
  WHERE R.BATCH_ID=:P_BATCH_ID AND D.SEVERITY='ERROR'
  GROUP BY R.EVENT_ID,R.BATCH_ID,R.TRADE_ID,R.VERSION,R.PAYLOAD,R.RAW_PAYLOAD,R.SOURCE_SYSTEM,R.SOURCE_FILE;

  RETURN 'CLASSIFIED '||P_BATCH_ID;
END;
$$;

-- Expiry is a lifecycle state, not a data-quality rejection.
CREATE OR REPLACE VIEW DB_TRADE_DB.CURATED.V_CURRENT_TRADES AS
SELECT *, IFF(MATURITY_DATE<CURRENT_DATE(),'EXPIRED','ACTIVE') AS DERIVED_LIFECYCLE_STATUS
FROM DB_TRADE_DB.CURATED.CURRENT_TRADES;
