CREATE DATABASE IF NOT EXISTS TRADE_DB;
CREATE SCHEMA IF NOT EXISTS TRADE_DB.RAW;
CREATE SCHEMA IF NOT EXISTS TRADE_DB.CURATED;
CREATE SCHEMA IF NOT EXISTS TRADE_DB.AUDIT;
CREATE SCHEMA IF NOT EXISTS TRADE_DB.MONITORING;

CREATE WAREHOUSE IF NOT EXISTS TRADE_PIPELINE_WH
  WAREHOUSE_SIZE='XSMALL' AUTO_SUSPEND=60 AUTO_RESUME=TRUE INITIALLY_SUSPENDED=TRUE;

CREATE FILE FORMAT IF NOT EXISTS TRADE_DB.RAW.TRADE_JSON_FORMAT
  TYPE=JSON STRIP_OUTER_ARRAY=FALSE IGNORE_UTF8_ERRORS=FALSE;
CREATE STAGE IF NOT EXISTS TRADE_DB.RAW.TRADE_STAGE
  FILE_FORMAT=TRADE_DB.RAW.TRADE_JSON_FORMAT;

CREATE TABLE IF NOT EXISTS TRADE_DB.RAW.TRADE_EVENTS (
  EVENT_ID STRING, TRADE_ID STRING, VERSION NUMBER(38,0), INSTRUMENT STRING,
  TRADE_SIDE STRING, QUANTITY NUMBER(38,8), PRICE NUMBER(38,8), CURRENCY STRING,
  TRADE_DATE DATE, MATURITY_DATE DATE, COUNTERPARTY STRING,
  EVENT_TIMESTAMP TIMESTAMP_NTZ, SOURCE_SYSTEM STRING, BATCH_ID STRING,
  INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(), RAW_PAYLOAD VARIANT
);

CREATE TABLE IF NOT EXISTS TRADE_DB.CURATED.CURRENT_TRADES (
  TRADE_ID STRING, VERSION NUMBER(38,0), INSTRUMENT STRING, TRADE_SIDE STRING,
  QUANTITY NUMBER(38,8), PRICE NUMBER(38,8), CURRENCY STRING, TRADE_DATE DATE,
  MATURITY_DATE DATE, COUNTERPARTY STRING, EVENT_TIMESTAMP TIMESTAMP_NTZ,
  SOURCE_SYSTEM STRING, BATCH_ID STRING, EVENT_ID STRING, TRADE_STATUS STRING,
  LAST_PROCESSED_AT TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS TRADE_DB.AUDIT.REJECTED_TRADES (
  EVENT_ID STRING, TRADE_ID STRING, VERSION NUMBER(38,0), REJECTION_REASON STRING,
  REJECTION_DETAILS STRING, SOURCE_SYSTEM STRING, BATCH_ID STRING,
  EVENT_TIMESTAMP TIMESTAMP_NTZ, RAW_PAYLOAD VARIANT,
  REJECTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS TRADE_DB.MONITORING.PIPELINE_RUNS (
  RUN_ID STRING, BATCH_ID STRING, STATUS STRING, STARTED_AT TIMESTAMP_NTZ,
  FINISHED_AT TIMESTAMP_NTZ, ROWS_LOADED NUMBER, ERROR_MESSAGE STRING
);
